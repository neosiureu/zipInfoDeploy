def item(api, umd, jibun="123", name="가나아파트", **kw):
    it = dict(_DEF)
    it["umdNm"] = umd
    it["jibun"] = jibun
    kind = api.split("_")[0]
    it[{"apt": "aptNm", "rh": "mhouseNm", "offi": "offiNm"}[kind]] = name
    if api.endswith("trade"):
        it["dealAmount"] = "50,000"
        it["cdealType"] = " "
    else:
        it["deposit"] = "30,000"
        it["monthlyRent"] = "0"
    if api == "apt_trade":
        it["landCd"] = "1"
        it["umdCd"] = ""
    if kind == "apt":
        it["aptSeq"] = ""
    it.update(kw)
    return it


def xml(total, items, rc="000"):
    from xml.sax.saxutils import escape
    body = "".join("<item>" + "".join(f"<{k}>{escape(v)}</{k}>" for k, v in it.items()) + "</item>" for it in items)
    return (f"<response><header><resultCode>{rc}</resultCode><resultMsg>OK</resultMsg></header>"
            f"<body><items>{body}</items><numOfRows>1000</numOfRows><pageNo>1</pageNo><totalCount>{total}</totalCount></body></response>").encode("utf-8")


def write_zip(path, bundles, apis, codes, months, top="snapshot_T"):
    """bundles: {(api, code, ym): [쪽1 항목들, 쪽2 항목들, ...]}. 없는 묶음은 0건 한 쪽으로 채운다."""
    import gzip
    import zipfile
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr(f"{top}/manifest.csv", "time,api\r\nx,y\r\n")
        for api in apis:
            for code in codes:
                for ym in months:
                    pages = bundles.get((api, code, ym), [[]])
                    total = sum(len(p) for p in pages)
                    for i, p in enumerate(pages, 1):
                        zf.writestr(f"{top}/raw/{api}/{code}/{ym}_p{i}.xml.gz", gzip.compress(xml(total, p)))
                    zf.writestr(f"{top}/raw/{api}/{code}/{ym}.done", f"{total}\r\n")
