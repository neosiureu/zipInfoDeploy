-- 5. rows left after the rollback (before COMMIT). Every REMAINING must be 0,
-- except the rehearsal fake member line, which stays 1 in the rehearsal and 0 in production.
SELECT 'STOCK_INFO' AS TABLE_NAME, COUNT(*) AS REMAINING FROM STOCK_INFO WHERE STOCK_NO IN (SELECT STOCK_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'SELL_DATE' AS TABLE_NAME, COUNT(*) AS REMAINING FROM SELL_DATE WHERE STOCK_NO IN (SELECT STOCK_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'STOCK_COORD' AS TABLE_NAME, COUNT(*) AS REMAINING FROM STOCK_COORD WHERE STOCK_NO IN (SELECT STOCK_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'STOCK_IMG' AS TABLE_NAME, COUNT(*) AS REMAINING FROM STOCK_IMG WHERE STOCK_NO IN (SELECT STOCK_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'LIKE_STOCK' AS TABLE_NAME, COUNT(*) AS REMAINING FROM LIKE_STOCK WHERE STOCK_NO IN (SELECT STOCK_NO FROM EXAMPLE_STOCK) OR MEMBER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'STOCK_SAW' AS TABLE_NAME, COUNT(*) AS REMAINING FROM STOCK_SAW WHERE STOCK_NO IN (SELECT STOCK_NO FROM EXAMPLE_STOCK) OR MEMBER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'MEMBER' AS TABLE_NAME, COUNT(*) AS REMAINING FROM MEMBER WHERE MEMBER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK) OR MEMBER_EMAIL = 'example-listings@example.invalid'
UNION ALL
SELECT 'TOKEN_INFO' AS TABLE_NAME, COUNT(*) AS REMAINING FROM TOKEN_INFO WHERE MEMBER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'BROKER_INFO' AS TABLE_NAME, COUNT(*) AS REMAINING FROM BROKER_INFO WHERE MEMBER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'HELP_MESSAGE' AS TABLE_NAME, COUNT(*) AS REMAINING FROM HELP_MESSAGE WHERE SENDER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK) OR RECEIVER_NO IN (SELECT DISTINCT MEMBER_NO FROM EXAMPLE_STOCK)
UNION ALL
SELECT 'REHEARSAL_FAKE_MEMBER (rehearsal only, should stay 1)', COUNT(*) FROM MEMBER WHERE MEMBER_EMAIL = 'rehearsal-fake-member@example.invalid';
